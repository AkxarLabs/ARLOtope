"""The PI's own instructions — added to a procedure, to a step, or to a subagent role — lab-wide (Workflow's
editors) or for one study (its page), and agents' proposals for them (take / leave). The files and the brief are
the kernel's (tools/kernel/instructions.py, brief.py); this is their API.
"""

from __future__ import annotations

import re
import sys

import ctx  # noqa: E402
from executor import procs  # noqa: E402
import sources  # noqa: E402
from kernel import brief as kbrief, instructions, model  # noqa: E402

executor = sources.executor   # tools/executor, or None


def inspect(q: dict) -> tuple[dict, int]:
    """Read instruction sources without launching, packaging skills or creating a draft."""
    from executor import contexts, Lab
    import skill_resources
    from kernel import checkpoints
    import compose

    sections, notices = [], []

    def add(title, path=None, text=None, raw=False, **extra):
        if path is not None:
            if not path.is_file():
                notices.append(f'{title}: no saved file is available.')
                return
            if path.stat().st_size > compose.MAX_FILE:
                notices.append(f'{title}: too large to display. Open the source file instead.')
                return
            text = path.read_text(encoding='utf-8-sig')
        if text and text.strip():
            sections.append({'title': title, 'text': text if raw else _body(text),
                             'source': str(path) if path else '', **extra})

    try:
        study = _study_arg(q.get('study'))
        draft = str(q.get('draft') or '') == '1'
        root = compose._root() if draft else ctx.HUB
        scope = 'Workflow draft' if draft else 'Published instructions'
        run = q.get('run_id')
        if run:
            from executor.manifest import find_run, run_dir
            hit = find_run(Lab(ctx.HUB), str(run))
            if not hit:
                return {'error': 'No such run.'}, 404
            directory = run_dir(hit[2].parent, str(run))
            scope = 'Recorded instructions'
            if not q.get('file'):
                add('Task prompt', directory / 'prompt.md', raw=True)
                add('Standing instructions', directory / 'preamble.md', raw=True)
            inventory = {p.parent.name: p.parent for p in (directory / 'skills').glob('*/SKILL.md')}
            if not inventory:
                notices.append('This run has no saved skill copies. Current skills are not substituted.')
            elif not q.get('file'):
                notices.append('Saved skill library: availability does not mean the agent read every skill.')
            names = [str(q['skill'])] if q.get('file') else sorted(inventory)
        else:
            project = checkpoints.project_dir(ctx.HUB, study) if study and not draft else None
            # Remote project skills require the remote runner. Never silently label the Lab copy as remote.
            import remote_projects
            remote = remote_projects.project(ctx.HUB, study) if study and not draft else None
            if remote:
                notices.append('Remote project skills are not read here. These are Lab definitions; a run records its resolved copies.')
                project = None
            inventory = skill_resources.folders(root, project)
            names = list(dict.fromkeys(filter(None, str(q.get('skills') or '').split(','))))
            if draft and study:
                notices.append('Shared workflow draft. A study can use its own project-local skills; inspect its task before starting.')
            if q.get('framework'):
                import frameworks
                external = {'framework': str(q['framework']), 'phase': str(q.get('phase') or '')}
                add('External tool instructions', text=frameworks.task_prompt(root, project or '<project>', study or '<study>', external),
                    source='Generated by tools/frameworks.py · project paths are filled when the study runs')
                names = list(dict.fromkeys([*names, 'external-framework']))
        if len(names) > 64:
            raise ValueError('Choose at most 64 skills.')
        for name in names:
            if not model.SLUG.fullmatch(name):
                raise ValueError('Choose a valid skill name.')
            folder = inventory.get(name)
            if folder is None:
                notices.append(f'Skill /{name} is not available in this source.')
                continue
            relative = str(q.get('file') or 'SKILL.md')
            path = (folder / relative).resolve()
            if not path.is_relative_to(folder.resolve()):
                raise ValueError('Choose a file within the skill folder.')
            refs = [p.relative_to(folder).as_posix() for p in folder.rglob('*')
                    if p.is_file() and p.resolve().is_relative_to(folder.resolve())
                    and p.suffix.lower() in compose.TEXT_EXT and p.name != 'SKILL.md']
            add(relative if q.get('file') else f'Skill · /{name}', path,
                skill=name, file=relative, code=path.suffix.lower() != '.md',
                files=sorted(refs) if not q.get('file') else [], **({'open': False} if run and not q.get('file') else {}))
        if not run and not q.get('file'):
            step, role = str(q.get('step') or ''), str(q.get('role') or '')
            primary = str(q.get('primary') or (names[0] if names else ''))
            for level in (None, study) if study else (None,):
                for name, kind in [(step, 'step'), ('' if primary == '-' else primary, 'add')]:
                    if not name:
                        continue
                    if not model.SLUG.fullmatch(name):
                        raise ValueError('Choose a valid instruction name.')
                    base = ctx.HUB if level else root
                    text = instructions.read(kind, name, base, level)
                    add(f'{"Study" if level else "Lab"} additions · {name}', text=text,
                        source=str(instructions.file(kind, name, base, level)))
            if role:
                if not model.SLUG.fullmatch(role):
                    raise ValueError('Choose a valid role.')
                path = root / 'agent-roles' / f'{role}.md'
                if not (root / 'agent-roles').is_dir() and role in model.roles(root):
                    path = model.CODE / 'agent-roles' / f'{role}.md'
                add(f'Role · {role}', path if path.is_file() else None,
                    text=None if path.is_file() else contexts._role_text(Lab(ctx.HUB), role),
                    **({} if path.is_file() else {'source': 'Task role definition'}))
                add('Lab role additions', text=instructions.read('role', role, root),
                    source=str(instructions.file('role', role, root)))
        return {'ok': True, 'scope': scope, 'sections': sections, 'notices': notices}, 200
    except (ValueError, OSError, UnicodeError) as error:
        return {'error': str(error)}, 400


def _study_arg(v) -> str | None:
    v = str(v or "").strip()
    if not v or v == "lab":
        return None
    if not re.match(r"^[a-z0-9][a-z0-9._-]{0,79}$", v) or not (ctx.HUB / "studies" / v).is_dir():
        raise ValueError(f"no study '{v}'")
    return v


def _body(text: str) -> str:
    text = (text or '').replace('\r\n', '\n')
    m = re.match(r"\A---\n.*?\n---\n?", text, re.S)
    return (text[m.end():] if m else text).strip()


def workflow_item(q: dict) -> tuple[dict, int]:
    """One procedure, step or role with the PI's added instructions on it — lab-wide, or one study's (and the
    brief an agent gets)."""
    hub = ctx.HUB
    kind = str(q.get("kind") or "procedure")
    name = str(q.get("name") or "")
    try:
        study = _study_arg(q.get("study"))
        m = model.load(hub)
        if kind == "procedure":
            p = m["procedures"].get(name)
            if not p:
                return {"error": f"unknown procedure '{name}'"}, 404
            out = {"ok": True, "kind": kind, "name": name, "study": study, "procedure": p,
                   "skill": _body(ctx.read(hub / ".claude" / "skills" / name / "SKILL.md") or ""),
                   "variants": sorted(n for n, x in m["procedures"].items() if x.get("like") == name),
                   "steps": [s for s, d in m["steps"].items() if name in [d.get("do"), *d["also"]]],
                   "lab": {"add": instructions.read("add", name, hub)}}
            if study:
                out["study_layer"] = {"add": instructions.read("add", name, hub, study)}
            out["brief"], out["brief_sha"] = kbrief.brief(hub, name, study=study)
            return out, 200
        if kind == "step":
            st = m["steps"].get(name)
            if not st:
                return {"error": f"unknown step '{name}'"}, 404
            out = {"ok": True, "kind": kind, "name": name, "study": study, "step": st,
                   "lab": {"add": instructions.read("step", name, hub)}}
            if study:
                out["study_layer"] = {"add": instructions.read("step", name, hub, study)}
            return out, 200
        if kind == "role":
            if name not in model.roles(hub):
                return {"error": f"unknown role '{name}'"}, 404
            return {"ok": True, "kind": kind, "name": name, "study": None,
                    "contract": (ctx.read(hub / "agent-roles" / f"{name}.md") or "").strip(),
                    "lab": {"add": instructions.read("role", name, hub)}}, 200
    except ValueError as e:
        return {"error": str(e)}, 400
    return {"error": "kind must be procedure | step | role"}, 400


def workflow_save(body: dict) -> tuple[dict, int]:
    """Save (empty text = remove) one set of added instructions: kind add | step | role, lab-wide or for a study."""
    hub = ctx.HUB
    kind, name = str(body.get("kind") or ""), str(body.get("name") or "")
    text = body.get("text")
    if kind not in instructions.KINDS or not isinstance(text, str):
        return {"error": "kind (add | step | role), name and text"}, 400
    try:
        study = _study_arg(body.get("study"))
        m = model.load(hub)
        known = {"add": m["procedures"], "step": m["steps"], "role": model.roles(hub)}[kind]
        if name not in known:
            return {"error": f"unknown {'procedure' if kind == 'add' else kind} '{name}'"}, 404
        path = instructions.write(kind, name, text, hub, study)
    except ValueError as e:
        return {"error": str(e)}, 400
    warnings = []
    if kind == "role":
        r = procs.run([sys.executable, str(hub / "tools" / "role_sync.py"), "render"], cwd=str(hub),
                           capture_output=True, text=True, timeout=120)
        if r.returncode != 0:
            warnings.append("saved, but re-rendering the role files failed: " + (r.stderr or r.stdout)[-300:])
    rel = path.relative_to(hub).as_posix() if path else None
    ctx.pi_log({"action": "workflow.save", "kind": kind, "name": name, "study": study, "chars": len(text.strip()),
               "file": rel})
    where = f"for {study}" if study else "lab-wide"
    return {"ok": True, "note": (f"saved {where}" if path else f"removed ({where})"), "file": rel,
            "warnings": warnings}, 200


def workflow_proposal(body: dict) -> tuple[dict, int]:
    """Take or leave an agent's suggested instructions."""
    pid, accept = str(body.get("id") or ""), body.get("accept")
    if not isinstance(accept, bool):
        return {"error": "accept must be true or false"}, 400
    try:
        rec = instructions.resolve(pid, accept, ctx.HUB)
    except (OSError, ValueError) as e:
        return {"error": str(e)}, 400
    if rec["kind"] == "role" and accept:
        procs.run([sys.executable, str(ctx.HUB / "tools" / "role_sync.py"), "render"], cwd=str(ctx.HUB),
                       capture_output=True, timeout=120)
    ctx.emit_hub("instruction_resolved", idea=rec.get("study"), detail=f"{rec['status']}: {rec['kind']} {rec['name']}")
    ctx.pi_log({"action": "workflow.proposal", "id": pid, "accept": accept, "kind": rec["kind"], "name": rec["name"],
               "study": rec.get("study")})
    return {"ok": True, "note": "added to the instructions" if accept else "declined"}, 200


def workflow_proposal_get(q: dict) -> tuple[dict, int]:
    pid = str(q.get("id") or "")
    for r in instructions.proposals(ctx.HUB, pending_only=False):
        if r.get("id") == pid:
            return {"ok": True, **r}, 200
    return {"error": "no such proposal"}, 404
