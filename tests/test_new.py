"""tools/new.py — adding to a lab by copying the closest thing it has: a skill (a variant), a step, a workflow, a
room, a role, a check, a project type, a rule. Each test works on a throwaway copy of this lab's definition, and
each change leaves the definition consistent (the kernel's check)."""

from __future__ import annotations

import json
import shutil

import pytest

from conftest import REPO, kernel, load

K = kernel()


@pytest.fixture
def lab(tmp_path):
    hub = tmp_path / "hub"
    for rel in ("workflow", ".claude/skills", "agent-roles", "checks", "templates/project-types"):
        shutil.copytree(REPO / rel, hub / rel)
    (hub / "lab").mkdir()
    (hub / "AGENTS.md").write_text("## Hard rules\n\n" + "<!-- newts:hard-rules (generated by `newts docs` "
                                    "from workflow/) -->\n<!-- /newts:hard-rules -->\n", encoding="utf-8")
    return hub


@pytest.fixture
def new():
    return load("new")


def _ok(lab):
    assert K.model.check(lab, K.rules.check_names(lab)) == [] and K.rules.check(lab) == []


def test_a_skill_variant_inherits_its_definition_and_can_be_offered_at_a_step(lab, new):
    new.new_skill(lab, "quick-scan", "lit-review", step="lit-review", title="A quick literature scan")
    skill = (lab / ".claude" / "skills" / "quick-scan" / "SKILL.md").read_text(encoding="utf-8")
    assert "name: quick-scan" in skill and "like: lit-review" in skill and "brief quick-scan" in skill
    p, base = K.model.procedure("quick-scan", lab), K.model.procedure("lit-review", lab)
    assert p["title"] == "A quick literature scan" and p["level"] == base["level"] and p["outputs"] == base["outputs"]
    assert "quick-scan" in K.model.step("lit-review", lab)["also"]
    _ok(lab)
    with pytest.raises(new.NewError):
        new.new_skill(lab, "quick-scan", "lit-review")


def test_a_step_is_copied_and_put_on_a_workflows_path(lab, new):
    new.new_step(lab, "replication", "active", do="experiment", label="Replication", workflow="research", after="analysis")
    st = K.model.step("replication", lab)
    assert (st["label"], st["do"], st["room"]) == ("Replication", "experiment", "lab")
    path = K.model.workflow("research", lab)["path"]
    assert path[path.index("analysis") + 1] == "replication"
    assert K.model.outcome_target("research", "analysis", "done", lab) == "replication"
    _ok(lab)
    with pytest.raises(new.NewError, match="already"):
        new.new_step(lab, "replication", "active")


def test_a_workflow_is_copied_with_checkpoints_of_its_own(lab, new):
    new.new_workflow(lab, "theory", "research", title="Theory")
    w = K.model.workflow("theory", lab)
    assert w["title"] == "Theory" and not w["default"] and all(c["id"].endswith("-theory") for c in w["checkpoints"])
    assert K.model.default_workflow(lab) == "research"
    _ok(lab)


def test_a_stage_group_copies_structure_without_visual_resources(lab, new):
    (lab / "lab" / "rooms3d").mkdir(parents=True, exist_ok=True)
    (lab / "lab" / "rooms3d" / "bench.json").write_text(json.dumps({"key": "bench", "size": [12, 8], "stations": {"analyze": [0, -2, 3.14]}}), encoding="utf-8")
    files = new.new_room(lab, "data", "bench", steps=["analysis"], title="The Data Room")
    assert not (lab / "lab" / "rooms3d" / "data.json").exists()
    rooms = {r["id"]: r for r in K.model.rooms(lab)}
    assert rooms["data"]["steps"] == ["analysis"] and "analysis" not in rooms["bench"]["steps"]
    assert "place" not in rooms["data"] and list(rooms)[-1] == "data"          # it takes the next free plot
    _ok(lab)
    assert files
    new.new_room(lab, "quiet", "margins")                                       # a built-in look is code: drawn plain
    assert not (lab / "lab" / "rooms3d" / "quiet.json").exists() and "quiet" in {r["id"] for r in K.model.rooms(lab)}


def test_a_role_like_another_inherits_its_settings(lab, new, monkeypatch):
    new.new_role(lab, "data-wrangler", "experiment-runner", label="Data wrangler")
    rs = load("role_sync")
    monkeypatch.setattr(rs, "HUB", lab)
    assert rs.role_keys()["data-wrangler"] == rs.role_keys()["experiment-runner"]
    assert (lab / ".claude" / "agents" / "data-wrangler.md").exists()
    assert K.model.roles(lab)["data-wrangler"] == "Data wrangler"


def test_a_check_and_a_type_and_a_rule(lab, new):
    new.new_check(lab, "no-tabs", "writeback")
    assert 'NAME = "no-tabs"' in (lab / "checks" / "no_tabs.py").read_text(encoding="utf-8")
    new.new_type(lab, "survey", "empirical")
    assert load("labfiles").project_types(lab)["survey"].startswith("# Project type: `survey`")
    new.new_rule(lab, "no-tabs", '**No tabs.** Indent with spaces: "always".', check="no-tabs")
    assert K.rules.check(lab) == []
    load("lab_docs").render(lab)
    assert '14. **No tabs.** Indent with spaces: "always".' in (lab / "AGENTS.md").read_text(encoding="utf-8")


def test_names_are_checked(lab, new):
    for bad in ("Has Space", "x", "../up", "UPPER"):
        with pytest.raises(new.NewError):
            new.new_skill(lab, bad, "lit-review")
    with pytest.raises(new.NewError):
        new.new_room(lab, "data", "nope")
    with pytest.raises(new.NewError, match="no procedure"):
        new.new_step(lab, "x-step", "active", do="nope")
