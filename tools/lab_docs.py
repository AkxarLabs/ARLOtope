"""The parts of the lab's manuals that are written from its definition — so they never drift from it.

    render(hub, check_only=False) -> [stale files]    `arlo docs` writes them; `arlo check` reports stale ones
    room_brief(hub, room) -> text                      what a stage group contains

Generated spans sit between `<!-- arlotope:<name> (generated …) -->` and `<!-- /arlotope:<name> -->` markers:
the rule lists and the workflows in AGENTS.md, the project rules in the project template's AGENTS.md, the head of
every procedure's SKILL.md (load the brief), the steps table in docs/workflow.md, and the
dashboard's built-in copy of the definition (dashboard/static/ui/workflow-default.js, for demo pages).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from kernel import model, rules

GEN = "generated by `arlo docs` from workflow/"
DOC_BEGIN = "<!-- workflow:begin (generated by `arlo docs` — edit workflow/) -->"
DOC_END = "<!-- workflow:end -->"
DOC_TARGETS = [Path("docs") / "workflow.md"]
SKILLS_BEGIN, SKILLS_END = "<!-- skills:begin -->", "<!-- skills:end -->"
PROJECT_MANUAL = Path("templates") / "project" / "AGENTS.md"
UI_DEFAULT = Path("dashboard") / "static" / "ui" / "workflow-default.js"
INLINE = {"project-types"}      # generated spans that sit inside a sentence


def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8-sig")
    except OSError:
        return ""


def _where(c: dict) -> str:
    return f"before `{c['before']}`" if c.get("before") else f"during `{c.get('during')}`, at {c.get('at')}"


def _numbered(items: list[dict]) -> str:
    return "\n".join(f"{i}. {r.get('text', '').strip()}" for i, r in enumerate(items, 1))


def workflows_line(hub=None) -> str:
    """Each workflow as one line: seed → … → proposal → [◆ Approve the proposal] → setup → … (AGENTS.md)."""
    out = []
    for w in model.workflows(hub):
        parts = []
        for s in w["path"]:
            parts += [f"[◆ {c['title']}]" for c in w["checkpoints"] if c.get("before") == s]
            parts.append(s)
            parts += [f"(◆ {c['title']}, at {c.get('at')})" for c in w["checkpoints"] if c.get("during") == s]
        out.append(f"- **{w.get('title') or w['id']}** (`{w['id']}`): `" + " → ".join(parts) + "`")
    return "\n".join(out)


def steps_table(hub=None) -> str:
    st = model.steps(hub)
    rows = ["| Step | Its procedure | Also | Room |", "|---|---|---|---|"]
    for s in st.values():
        if s["shelf"]:
            continue
        rows.append(f"| `{s['id']}` — {s['label']} | " + (f"`/{s['do']}`" if s.get("do") else "") + " | "
                    + ", ".join(f"`/{p}`" for p in s["also"]) + f" | {s.get('room') or ''} |")
    rows += ["", "| Workflow | Path | Routes | Checkpoints |", "|---|---|---|---|"]
    for w in model.workflows(hub):
        routes = "; ".join(f"{a}: " + ", ".join(f"`{o}` → {t}" for o, t in v.items()) for a, v in w["routes"].items())
        rows.append(f"| {w.get('title') or w['id']} (`{w['id']}`){' — default' if w['default'] else ''} | "
                    + " → ".join(f"`{s}`" for s in w["path"]) + f" | {routes or '—'} | "
                    + ("; ".join(f"{c['title']} ({_where(c)})" for c in w["checkpoints"]) or "none") + " |")
    return "\n".join(rows)


def contract_block(proc: str, hub=None) -> str:
    """The generated head of a procedure's SKILL.md: load the brief (it states the outcomes, outputs and what to show the PI)."""
    p = model.procedure(proc, hub) or {}
    project = p.get("level") == "project"
    arlo = "<hub>/arlo.py" if project else "arlo.py"
    study = "slug" in str(p.get("args", ""))
    lines = [f"**First, load the brief:** `{arlo} brief {proc}" + (" --study <slug>`" if study else " [--study <slug>]`")
             + (" (`<hub>` = this project's `control.yaml` `hub_path`)" if project else "")
             + f"; skip when `ARLOTOPE BRIEF /{proc}` is already supplied. It states how to finish, what to produce and show the PI, "
             "and the PI's additions and checkpoints."]
    if p.get("guide"):
        where = "<hub>/AGENT-GUIDE.md" if project else "AGENT-GUIDE.md"
        lines.append(f"**Read first:** `{where}` — " + ", ".join(f"\"{g}\"" for g in p["guide"]) + ".")
    return "\n".join(lines)


def project_types_line(hub=None) -> str:
    root = model.hub_of(hub) / "templates" / "project-types"
    out = []
    for d in sorted(root.iterdir()) if root.is_dir() else []:
        head = _read(d / "TYPE.md").split("\n", 1)[0]
        if head:
            out.append(f"`{d.name}`" + (" (default)" if "(default)" in head else ""))
    return " · ".join(out)


def skills_list(hub=None) -> str:
    return ", ".join(f"`{n}`" for n, p in model.load(hub)["procedures"].items() if not p.get("engineering"))


def ui_default_js(hub=None) -> str:
    return ("/* GENERATED by `arlo docs` from workflow/ — do not edit. The live snapshot's `workflow` replaces\n"
            "   this; it only serves demo/static pages. */\n"
            "window.__WORKFLOW_DEFAULT__ = " + json.dumps(model.view(hub), ensure_ascii=False, sort_keys=True) + ";\n")


def _span(name: str) -> tuple[str, str]:
    return f"<!-- arlotope:{name} ({GEN}) -->", f"<!-- /arlotope:{name} -->"


def _blocks(hub) -> list[tuple[Path, str, str]]:
    rl = rules.load(hub)
    out = [(Path("AGENTS.md"), "hard-rules", _numbered(rl.get("hard_rules") or [])),
           (Path("AGENTS.md"), "subagent-rules", _numbered(rl.get("subagent_rules") or [])),
           (Path("AGENTS.md"), "lifecycle", workflows_line(hub)),
           (PROJECT_MANUAL, "project-rules", _numbered(rl.get("project_rules") or [])),
           (Path("AGENTS.md"), "project-types", project_types_line(hub)),
           (model.SKILLS / "spawn-project" / "SKILL.md", "project-types", project_types_line(hub))]
    for name, p in model.load(hub)["procedures"].items():
        file = Path(hub) / model.SKILLS / name / 'SKILL.md'
        if not p.get("engineering") and file.is_file() and model.skill_meta(_read(file)).get('arlotope'):
            out.append((model.SKILLS / name / "SKILL.md", "contract", contract_block(name, hub)))
    return out


def _put(p: Path, new: str, txt: str, check_only: bool, stale: list, rel: Path) -> None:
    if new != txt:
        stale.append(rel)
        if not check_only:
            p.write_text(new, encoding="utf-8", newline="")


def render(hub=None, check_only: bool = False) -> list[Path]:
    hub = model.hub_of(hub)
    stale: list[Path] = []
    js = hub / UI_DEFAULT
    if js.parent.is_dir():
        want = ui_default_js(hub)
        if _read(js) != want:
            stale.append(UI_DEFAULT)
            if not check_only:
                js.write_text(want, encoding="utf-8", newline="\n")
    block = f"{DOC_BEGIN}\n{steps_table(hub)}\n{DOC_END}"
    for rel in DOC_TARGETS:
        p, txt = hub / rel, _read(hub / rel)
        if DOC_BEGIN in txt and DOC_END in txt:
            _put(p, re.sub(re.escape(DOC_BEGIN) + r".*?" + re.escape(DOC_END), lambda _m: block, txt, flags=re.S),
                 txt, check_only, stale, rel)
    for rel, name, content in _blocks(hub):
        p, txt = hub / rel, _read(hub / rel)
        begin, end = _span(name)
        old = re.search(r"<!-- arlotope:" + re.escape(name) + r" \([^)]*\) -->", txt)   # any older marker wording
        if not old or end not in txt:
            continue
        nl = "\r\n" if "\r\n" in txt else "\n"
        body = content.replace("\n", nl)
        gen = f"{begin}{body}{end}" if name in INLINE else f"{begin}{nl}{body}{nl}{end}"
        _put(p, re.sub(re.escape(old.group(0)) + r".*?" + re.escape(end), lambda _m: gen, txt, count=1, flags=re.S),
             txt, check_only, stale, rel)
    p, txt = hub / "AGENTS.md", _read(hub / "AGENTS.md")
    if SKILLS_BEGIN in txt and SKILLS_END in txt:
        _put(p, re.sub(re.escape(SKILLS_BEGIN) + r".*?" + re.escape(SKILLS_END),
                       lambda _m: f"{SKILLS_BEGIN}{skills_list(hub)}{SKILLS_END}", txt, flags=re.S),
             txt, check_only, stale, Path("AGENTS.md"))
    return stale


def room_brief(hub, rid: str) -> str | None:
    """What a stage group holds: its steps, the procedures that need a station, its lanterns.
    Looks in the lab, then in the PI's open Compose draft (a room added there but not published yet)."""
    h = model.hub_of(hub)
    rid, _, ptype = rid.partition(".")       # `lab.ml`: the look of a Lab for one project type
    for root in (h, h / "lab" / ".bus" / "compose" / "draft"):
        if root != h and not (root / model.STEPS).is_file():
            continue
        try:
            m = model.load(root)
        except Exception:  # noqa: BLE001 — an unreadable draft is skipped
            continue
        room = next((r for r in model.rooms(root) if r["id"] == rid), None)
        if not room:
            continue
        steps = room["steps"]
        procs = list(dict.fromkeys(p for s in steps for p in [m["steps"][s].get("do"), *m["steps"][s]["also"]] if p))
        lanterns = [c for w in m["workflows"] for c in w["checkpoints"] if c.get("before") in steps or c.get("during") in steps]
        look = f"{rid}.{ptype}" if ptype else rid
        roles = sorted(f.stem for f in (h / "agent-roles").glob("*.yaml")) if (h / "agent-roles").is_dir() else []
        return "\n".join([
            f"ROOM {look} — {room.get('title') or room.get('label') or rid}" + ("  (in the PI's draft)" if root != h else "")
            + (f" — the look of every {rid} whose project is of type {ptype!r}: make it say {ptype} at a glance "
               f"(the type's conventions: templates/project-types/{ptype}/TYPE.md); key it \"{look}\"" if ptype else ""),
            "steps: " + (", ".join(f"{s} ({m['steps'][s]['label']})" for s in steps) or "none — studies only rest here"),
            "procedures (each needs a station): " + (", ".join(f"{p} — {(m['procedures'].get(p) or {}).get('title', p)}" for p in procs) or "none"),
            "checkpoints (a lantern each): " + ("; ".join(str(g.get("title")) for g in lanterns) or "none"),
            "subagent roles that may work here: " + ", ".join(roles),
            "Rooms group tasks visually. Use the room designer's private preview before applying changes."])
    return None
